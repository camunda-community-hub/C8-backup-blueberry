package io.camunda.blueberry.platform.version;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

class BlueberryVersionTest {

    @Test
    void theVersionIsInThePomPropertiesOfTheJar() {
        String properties = "#Generated by Maven\nartifactId=blueberry\ngroupId=io.camunda.community\nversion=2.0.0\n";
        assertEquals("2.0.0", BlueberryVersion.fromPomProperties(new ByteArrayInputStream(properties.getBytes(StandardCharsets.UTF_8))));
        assertNull(BlueberryVersion.fromPomProperties(null));
        assertNull(BlueberryVersion.fromPomProperties(new ByteArrayInputStream("artifactId=blueberry".getBytes(StandardCharsets.UTF_8))));
    }

    @Test
    void theVersionIsInThePomWhenBlueberryRunsFromTheIde(@TempDir Path directory) throws Exception {
        Path pom = directory.resolve("pom.xml");
        Files.writeString(pom, "<project><modelVersion>4.0.0</modelVersion><groupId>g</groupId><artifactId>a</artifactId>"
                + "<version>2.3.4</version></project>");
        assertEquals("2.3.4", new BlueberryVersion().fromPomXml(pom));
    }

    @Test
    void theVersionOfTheParentIsUsedWhenTheProjectHasNone(@TempDir Path directory) throws Exception {
        Path pom = directory.resolve("pom.xml");
        Files.writeString(pom, "<project><modelVersion>4.0.0</modelVersion><parent><groupId>p</groupId><artifactId>p</artifactId>"
                + "<version>5.0.0</version></parent><artifactId>a</artifactId></project>");
        assertEquals("5.0.0", new BlueberryVersion().fromPomXml(pom));
    }

    @Test
    void noPomNoVersion(@TempDir Path directory) {
        assertNull(new BlueberryVersion().fromPomXml(directory.resolve("missing.xml")));
    }
}
